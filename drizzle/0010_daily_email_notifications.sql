CREATE TABLE `daily_email_notifications` (
  `id` int NOT NULL AUTO_INCREMENT,
  `employeeId` int NOT NULL,
  `employeeCode` varchar(20) NOT NULL,
  `employeeName` varchar(120) NOT NULL,
  `employeeEmail` varchar(320) NOT NULL,
  `notificationDate` date NOT NULL,
  `emailSubject` varchar(255) NOT NULL,
  `scheduledVisitCount` int NOT NULL DEFAULT 0,
  `rescheduledVisitCount` int NOT NULL DEFAULT 0,
  `followUpCount` int NOT NULL DEFAULT 0,
  `overdueFollowUpCount` int NOT NULL DEFAULT 0,
  `resendMessageId` varchar(255),
  `deliveryStatus` enum('Processing','Sent','Failed','Resent') NOT NULL DEFAULT 'Processing',
  `attemptType` enum('Automatic','Manual','Test') NOT NULL DEFAULT 'Automatic',
  `idempotencyKey` varchar(128),
  `parentNotificationId` int,
  `htmlSnapshot` text,
  `errorDetails` text,
  `sentAt` timestamp NULL,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `daily_email_notifications_idempotency_uq` (`idempotencyKey`),
  KEY `daily_email_notifications_date_idx` (`notificationDate`),
  KEY `daily_email_notifications_employee_date_idx` (`employeeId`,`notificationDate`),
  KEY `daily_email_notifications_parent_idx` (`parentNotificationId`),
  CONSTRAINT `daily_email_notifications_employee_fk` FOREIGN KEY (`employeeId`) REFERENCES `employees` (`id`) ON DELETE RESTRICT
);
